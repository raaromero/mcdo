"""What the annular sweeps actually show, written from the saved numbers.

There are four moving parts — numerical aperture, input illumination,
obstruction ratio, pulse duration — and with that many axes a hand-written
summary drifts from the data within a week. This reads the two sweeps and
states, for every configuration, what it does on its own and how it compares
against the references that matter:

    against its own unobstructed disk   (what the ring did)
    against uniform illumination        (what the input did)
    against continuous wave             (what the bandwidth did)
    against the paraxial law            (whether the textbook result holds)

Writes docs/ANNULAR_OBSERVATIONS.md. Recomputes nothing.
"""

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..'))

import numpy as np

ROOT = os.path.join(os.path.dirname(__file__), '..')
BASE = os.path.join(ROOT, 'output', '03_annular', 'annular_baseline.npz')
PULSED = os.path.join(ROOT, 'output', '05_pulsed_pupils', 'pulsed_annular_grid.npz')
DOC = os.path.join(ROOT, 'docs', 'ANNULAR_OBSERVATIONS.md')

UNIFORM = 'uniform'
GAUSS = 'Gaussian, alpha = 4'


def _load(path, keys):
    d = np.load(path, allow_pickle=True)
    n = len(d['eps'])
    rows = []
    for i in range(n):
        row = {k: (str(d[k][i]) if d[k].dtype.kind in 'US' else float(d[k][i]))
               for k in keys if k in d}
        rows.append(row)
    return rows


def _pick(rows, **kw):
    for r in rows:
        if all(abs(r[k] - v) < 1e-9 if isinstance(v, float) else r[k] == v
               for k, v in kw.items()):
            return r
    return None


def main():
    if not os.path.exists(BASE):
        raise SystemExit(f"{BASE} not found — run verify_annular_baseline.py first")

    base = _load(BASE, ['na', 'input', 'eps', 'width_nm', 'depth_um', 'gain',
                        'peak', 'extent_um', 'extent_gain', 'sidelobe',
                        'transmission'])
    pulsed = (_load(PULSED, ['na', 'input', 'eps', 'tau', 'width_nm',
                             'depth_um', 'gain', 'peak'])
              if os.path.exists(PULSED) else [])

    na_vals = sorted({r['na'] for r in base})
    eps_vals = sorted({r['eps'] for r in base})

    out = ["# What the annular sweeps show",
           "",
           "Generated by `scripts/annular_observations.py` from the saved sweeps.",
           "Do not edit by hand: rerun the script instead.",
           "",
           "Held fixed throughout: center wavelength 750 nm, refractive index 1.3,",
           "Gaussian alpha = 4, total intensity of all three field",
           "components.",
           ""]

    # ── per configuration, on its own and against each reference ──────────
    out += ["## Continuous-wave baseline", ""]
    for na in na_vals:
        out += [f"### Numerical aperture {na:g}", ""]
        out += ["| Ratio | Input | Width (nm) | Depth (µm) | Gain | vs paraxial |"
                " Transmission | Peak | Side lobe |",
                "|---|---|---|---|---|---|---|---|---|"]
        for eps in eps_vals:
            law = 1.0 / (1.0 - eps ** 2)
            for label, short in ((UNIFORM, 'uniform'), (GAUSS, 'Gaussian')):
                r = _pick(base, na=na, input=label, eps=eps)
                if r is None:
                    continue
                rel = r['gain'] / law
                out.append(
                    f"| {eps:g} | {short} | {r['width_nm']:.0f} | "
                    f"{r['depth_um']:.2f} | {r['gain']:.2f} | {rel:.0%} | "
                    f"{r.get('transmission', float('nan')):.3f} | "
                    f"{r['peak']:.3f} | {r.get('sidelobe', float('nan')):.3f} |")
        out.append("")

        # the observations themselves, stated from the numbers
        u0 = _pick(base, na=na, input=UNIFORM, eps=0.0)
        g0 = _pick(base, na=na, input=GAUSS, eps=0.0)
        notes = []
        if u0 and g0:
            notes.append(
                f"Without a ring, Gaussian input widens the focus from "
                f"{u0['width_nm']:.0f} nm to {g0['width_nm']:.0f} nm "
                f"({g0['width_nm'] / u0['width_nm'] - 1:+.0%}): truncation "
                f"discards the marginal rays that make the spot tight.")
        hi = max(eps_vals)
        uh, gh = _pick(base, na=na, input=UNIFORM, eps=hi), _pick(base, na=na, input=GAUSS, eps=hi)
        if uh and gh:
            spread = abs(uh['width_nm'] - gh['width_nm']) / uh['width_nm']
            if spread < 0.02:
                notes.append(
                    f"At obstruction {hi:g} the two inputs give the same focus "
                    f"({uh['width_nm']:.0f} nm against {gh['width_nm']:.0f} nm): a thin "
                    f"ring passes only edge rays, so how the pupil was lit stops "
                    f"mattering.")
        for label, short in ((UNIFORM, 'uniform'), (GAUSS, 'Gaussian')):
            below = [e for e in eps_vals
                     if (_pick(base, na=na, input=label, eps=e) or {}).get('gain', 9) < 1.0]
            if below:
                notes.append(
                    f"With {short} illumination the extension falls below unity at "
                    f"obstruction ratio {min(below):g}: the stop shortens the focus "
                    f"rather than extending it.")
        for eps in (0.9, 0.99):
            r = _pick(base, na=na, input=UNIFORM, eps=eps)
            if r:
                law = 1.0 / (1.0 - eps ** 2)
                notes.append(
                    f"At obstruction {eps:g} the paraxial law predicts {law:.1f}x and "
                    f"the computed gain is {r['gain']:.1f}x "
                    f"({r['gain'] / law:.0%} of it).")
            if r and 'extent_gain' in r and np.isfinite(r['extent_gain']):
                if abs(r['extent_gain'] / r['gain'] - 1) > 0.25:
                    notes.append(
                        f"At obstruction {eps:g} the half-maximum width and the "
                        f"80% energy extent disagree "
                        f"({r['gain']:.1f}x against {r['extent_gain']:.1f}x), so the "
                        f"focus is no longer a single lobe and the width alone "
                        f"is not a fair description.")
        out += ["**Observations**", ""] + [f"- {n}" for n in notes] + [""]

    # ── what the bandwidth did, against the same baseline ─────────────────
    if pulsed:
        out += ["## What pulsing changes", "",
                "Each cell against its own continuous-wave value at the same "
                "aperture, input and obstruction ratio.", "",
                "| NA | Input | Ratio | Gain, continuous wave | Gain, 1 fs | Change |",
                "|---|---|---|---|---|---|"]
        for na in sorted({r['na'] for r in pulsed}):
            for label, short in ((UNIFORM, 'uniform'), (GAUSS, 'Gaussian')):
                for eps in sorted({r['eps'] for r in pulsed}):
                    cw = _pick(pulsed, na=na, input=label, eps=eps,
                               tau='continuous wave')
                    fs = _pick(pulsed, na=na, input=label, eps=eps, tau='1 fs')
                    if not cw or not fs or eps == 0.0:
                        continue
                    if not (np.isfinite(cw['gain']) and np.isfinite(fs['gain'])):
                        continue
                    out.append(
                        f"| {na:g} | {short} | {eps:g} | {cw['gain']:.2f} | "
                        f"{fs['gain']:.2f} | {fs['gain'] / cw['gain'] - 1:+.1%} |")
        out.append("")

    with open(DOC, 'w') as fh:
        fh.write("\n".join(out) + "\n")
    print(f"Saved → {DOC}  ({len(out)} lines)")


if __name__ == '__main__':
    main()
